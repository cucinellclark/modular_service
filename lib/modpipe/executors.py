"""Executors: run a materialized job graph. Both run the same per-job scripts (.modpipe/job.sh)."""
import os
import shlex
import subprocess
import sys
import time


class ExecutionError(Exception):
    pass


def _log(msg):
    print(f"[modpipe {time.strftime('%H:%M:%S')}] {msg}", file=sys.stderr, flush=True)


class LocalExecutor:
    """Minimal scheduler: runs ready jobs in parallel within a CPU and memory budget. Used for dev and tests."""

    name = "local"

    def __init__(self, cores, mem_gb, resume=False):
        self.cores, self.mem_gb, self.resume = cores, mem_gb, resume

    def run(self, jobs, rundir):
        done, failed, running = set(), {}, {}
        if self.resume:
            done = {j.id for j in jobs.values() if os.path.exists(j.marker)}
            if done:
                _log(f"resume: {len(done)} job(s) already complete")
        pending = [j for j in jobs.values() if j.id not in done]
        while pending or running:
            # launch
            free_cpu = self.cores - sum(j.cpu for j in running.values())
            free_mem = self.mem_gb - sum(j.mem_gb for j in running.values())
            if not failed:
                for j in list(pending):
                    if not j.deps <= done:
                        continue
                    if running and (j.cpu > free_cpu or j.mem_gb > free_mem):
                        continue
                    log = open(os.path.join(j.workdir, ".modpipe", "job.log"), "w")
                    p = subprocess.Popen(["bash", j.script], stdout=log, stderr=subprocess.STDOUT)
                    p._log = log
                    running[j.id] = j
                    j._proc, j._t0 = p, time.time()
                    pending.remove(j)
                    free_cpu -= j.cpu
                    free_mem -= j.mem_gb
                    _log(f"start  {j.id} ({j.module.id}, {j.cpu} cpu)")
            elif not running:
                break
            if not running and pending and not failed:
                raise ExecutionError(f"deadlock: jobs {[j.id for j in pending]} can never start")
            # reap
            time.sleep(0.5)
            for jid, j in list(running.items()):
                rc = j._proc.poll()
                if rc is None:
                    continue
                j._proc._log.close()
                del running[jid]
                dt = time.time() - j._t0
                if rc == 0:
                    done.add(jid)
                    _log(f"done   {jid} in {dt:.1f}s")
                else:
                    failed[jid] = rc
                    _log(f"FAILED {jid} (exit {rc}) after {dt:.1f}s; see {os.path.relpath(j.workdir, rundir)}/.modpipe/")
                    with open(os.path.join(j.workdir, ".modpipe", "job.log")) as f:
                        for line in f.read().splitlines()[-15:]:
                            print("    " + line, file=sys.stderr)
        if failed:
            skipped = [j.id for j in pending]
            raise ExecutionError(f"failed: {sorted(failed)}" + (f"; not run: {skipped}" if skipped else ""))


class SnakemakeExecutor:
    """Generates a Snakefile with one rule per job (dependencies via completion markers) and runs Snakemake 7."""

    name = "snakemake"

    def __init__(self, cores, mem_gb, resume=False, snakemake="snakemake", extra_args=None):
        self.cores, self.mem_gb, self.resume = cores, mem_gb, resume
        self.snakemake, self.extra = snakemake, extra_args or []

    def write_snakefile(self, jobs, rundir):
        path = os.path.join(rundir, ".modpipe", "Snakefile")
        rel = lambda p: os.path.relpath(p, rundir)
        lines = ["# Generated by modpipe. One rule per job; .modpipe/done markers carry dependencies.", "",
                 "rule all:", "    input:"]
        lines += [f"        {rel(j.marker)!r}," for j in jobs.values()]
        lines.append("")
        for i, j in enumerate(jobs.values()):
            inputs = [rel(jobs[d].marker) for d in sorted(j.deps)] + sorted(set(j.external_inputs))
            lines += [f"# {j.id}: {j.module.id} v{j.module.version}",
                      f"rule j{i}_{j.id.replace('-', '_').replace('.', '_')}:"]
            if inputs:
                lines.append("    input:")
                lines += [f"        {x!r}," for x in inputs]
            lines += ["    output:", f"        {rel(j.marker)!r},",
                      f"    threads: {j.cpu}",
                      f"    resources: mem_mb={int(j.mem_gb * 1024)}",
                      f"    log: {rel(os.path.join(j.workdir, '.modpipe', 'job.log'))!r}",
                      f"    shell: {('bash ' + shlex.quote(rel(j.script)) + ' > {log} 2>&1')!r}", ""]
        with open(path, "w") as f:
            f.write("\n".join(lines))
        return path

    def run(self, jobs, rundir):
        sf = self.write_snakefile(jobs, rundir)
        cmd = [self.snakemake, "-s", sf, "--directory", rundir, "--cores", str(self.cores),
               "--resources", f"mem_mb={int(self.mem_gb * 1024)}", "--nolock", "--rerun-incomplete",
               "--printshellcmds", "--show-failed-logs"] + self.extra
        if not self.resume:
            cmd.append("--forceall")
        _log("snakemake: " + " ".join(shlex.quote(c) for c in cmd))
        p = subprocess.run(cmd)
        if p.returncode != 0:
            failed = [j.id for j in jobs.values() if not os.path.exists(j.marker)]
            raise ExecutionError(f"snakemake exited {p.returncode}; incomplete jobs: {failed}")

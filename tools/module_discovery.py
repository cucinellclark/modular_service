#!/usr/bin/env python3
"""Generate a P4 discovery set whose commands are rendered from the real module descriptors.

    python3 tools/module_discovery.py tools/module_discovery_specs.yaml tests/discovery/sets/NN_name.yaml

Each spec: {run_id, module, inputs: {port: fixture id | [fixture ids]}, params: {...}}. Inputs use the fetched
fixture paths (tests/fixtures/data/fixtures_index.json). A port that requires compression: none and gets a .gz
fixture is decompressed in the run's `prep`. The rendered command is exactly what the module would run, so
`modpipe lint` can check the module's declared outputs against the result.
"""
import os
import shlex
import sys

import yaml

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from modpipe.registry import DatabaseRegistry, ModuleRegistry  # noqa: E402
from modpipe.template import (Value, build_context, db_context, output_value, render_command,  # noqa: E402
                              resolve_output_type)
from modpipe.types import TypeSystem  # noqa: E402
from modpipe.util import read_json, repo_path  # noqa: E402


def main(spec_file, out_file):
    ts, dbs = TypeSystem(), DatabaseRegistry()
    mods = ModuleRegistry(ts, dbs)
    fx = read_json(repo_path("tests", "fixtures", "data", "fixtures_index.json"))["fixtures"]
    manifest = {f["id"]: f for f in read_json(repo_path("tests", "fixtures", "manifest.json"))["fixtures"]}
    spec = yaml.safe_load(open(spec_file))
    runs = []
    for r in spec["runs"]:
        m = mods.get(r["module"])
        prep, inputs, input_types = [], {}, {}
        for pid, port in m.inputs.items():
            ids = r["inputs"].get(pid)
            if ids is None:
                inputs[pid] = None
                continue
            many = port.get("cardinality", "one") == "many"
            vals = []
            for fid in (ids if isinstance(ids, list) else [ids]):
                t = r.get("types", {}).get(pid) or manifest[fid]["type"]
                path = fx[fid]
                attrs = dict(ts.fixed_attributes(t))
                attrs["compression"] = "gzip" if path.endswith(".gz") else "none"
                if (port.get("requires") or {}).get("compression") == "none" and path.endswith(".gz"):
                    local = f"in_{pid}_{os.path.basename(path)[:-3]}"
                    prep.append(f"gzip -dc {shlex.quote(path)} > {local}")
                    path, attrs["compression"] = local, "none"   # runs execute in their own work dir
                vals.append(Value(t, path=path, attrs=attrs, ts=ts, label=fid))
            if r.get("pairs", {}).get(pid):                    # paired reads given as [r1, r2]
                a, b = vals
                vals = [Value(r["pairs"][pid], parts={"r1": a._path, "r2": b._path},
                              attrs={**ts.fixed_attributes(r["pairs"][pid]), "compression": a.attrs["compression"]},
                              ts=ts, label=pid)]
            inputs[pid] = vals if many else vals[0]
            input_types[pid] = vals[0].type
        params = {k: s.get("default") for k, s in m.params.items()}
        params.update(r.get("params") or {})
        outs = {o: output_value(op, resolve_output_type(m, op, input_types, ts) or op["type"], ts) for o, op in m.outputs.items()}
        d, df = db_context(m, params, dbs, resolve=lambda e: repo_path(e["path"]) if e.get("location") == "repo_fixture"
                           else e.get("path", ""))
        res = spec.get("resources", {"cpu": 4, "mem": "16G"})
        cpu, mem = int(res.get("cpu", 4)), int(str(res.get("mem", "16G")).rstrip("Gg"))
        cmd = render_command(m, build_context(m, inputs, outs, params, cpu, mem, d, df))
        runs.append({"id": r["run_id"], "tool": m.d["tool"]["id"], "mode": f"module_{m.id}",
                     "description": f"rendered from modules/{m.id}.yaml (tools/module_discovery.py)",
                     **({"prep": "\n".join(prep) + "\n"} if prep else {}), "cmd": cmd})
    out = {"set": spec["set"], "resources": spec.get("resources", {"cpu": 4, "mem": "16G", "time": "01:00:00"}), "runs": runs}
    with open(out_file, "w") as f:
        f.write(f"# Generated by tools/module_discovery.py from {os.path.relpath(spec_file, repo_path())}; do not edit.\n")
        yaml.safe_dump(out, f, sort_keys=False, width=200)
    print(f"wrote {out_file}: {len(runs)} runs")


if __name__ == "__main__":
    main(*sys.argv[1:3])
